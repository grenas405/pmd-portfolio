#!/usr/bin/env node
/**
 * Bundles client/ into content-hashed files under public/assets/ and writes
 * src/assets.gen.ts so the Worker can reference the hashed paths.
 * Usage: node scripts/build-client.mjs
 */
import { build } from "esbuild";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";

const OUT_DIR = "public/assets";
const MANIFEST = "src/assets.gen.ts";

const toUrl = (file) => "/" + relative("public", file).split("\\").join("/");

/** Pick the single output whose entry or extension matches. Fails loudly if missing. */
const findOutput = (outputs, predicate, label) => {
  const match = Object.entries(outputs).find(([file, meta]) => predicate(file, meta));
  if (!match) throw new Error(`build-client: no ${label} output found`);
  return toUrl(match[0]);
};

const main = async () => {
  // Empty the directory rather than replacing it: `wrangler dev` stops serving
  // assets from a directory that is deleted and recreated while it watches.
  await mkdir(OUT_DIR, { recursive: true });
  for (const file of await readdir(OUT_DIR)) await rm(join(OUT_DIR, file), { recursive: true, force: true });

  const result = await build({
    entryPoints: { app: "client/main.js", styles: "client/styles/main.css" },
    outdir: OUT_DIR,
    entryNames: "[name]-[hash]",
    assetNames: "[name]-[hash]",
    bundle: true,
    minify: true,
    format: "esm",
    target: ["es2022", "chrome111", "firefox113", "safari16.4"],
    loader: { ".woff2": "file" },
    legalComments: "eof",
    metafile: true,
    logLevel: "warning",
  });

  const { outputs } = result.metafile;
  const assets = {
    js: findOutput(outputs, (_f, meta) => meta.entryPoint === "client/main.js", "JavaScript"),
    css: findOutput(outputs, (_f, meta) => meta.entryPoint === "client/styles/main.css", "CSS"),
    font: findOutput(outputs, (file) => /archivo-.*\.woff2$/.test(file), "Archivo font"),
  };

  const source = `// Generated by scripts/build-client.mjs — do not edit.\nimport type { Assets } from "./views/types";\n\nexport const assets: Assets = ${JSON.stringify(assets, null, 2)};\n`;
  await writeFile(MANIFEST, source);

  const sizes = Object.entries(outputs).map(([file, meta]) => `  ${file} ${(meta.bytes / 1024).toFixed(1)} KiB`);
  console.log(`build-client: wrote ${MANIFEST}\n${sizes.join("\n")}`);
};

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
